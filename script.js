const progress = document.querySelector(".progress");
let dragging = false;
let scrubPointer = null;
let pendingTime = 0;

function renderProgress(seconds){
  const duration=Number.isFinite(audio.duration)?audio.duration:0;
  const percent=duration>0?clamp(seconds/duration,0,1)*100:0;
  document.getElementById("progressBar").style.width=percent+"%";
  document.getElementById("currentTime").textContent=formatTime(seconds);
  progress.setAttribute("aria-valuenow",String(Math.round(percent)));
  progress.setAttribute("aria-valuetext",formatTime(seconds)+" / "+formatTime(duration));
}

function previewProgress(e){
  const rect = progress.getBoundingClientRect();
  const percent=clamp((e.clientX-rect.left)/rect.width,0,1);
  pendingTime=percent*audio.duration;
  renderProgress(pendingTime);
}

function cancelScrub(){
  const pointer=scrubPointer;
  dragging=false;
  scrubPointer=null;
  if(pointer!==null&&progress.hasPointerCapture(pointer)) progress.releasePointerCapture(pointer);
}

progress.addEventListener("pointerdown",(e)=>{
  if(dragging||!e.isPrimary||e.button!==0||!Number.isFinite(audio.duration)||audio.duration<=0) return;
  e.preventDefault();
  dragging=true;
  scrubPointer=e.pointerId;
  progress.setPointerCapture(e.pointerId);
  progress.focus({preventScroll:true});
  previewProgress(e);
});

progress.addEventListener("pointermove",(e)=>{
  if(dragging&&e.pointerId===scrubPointer) previewProgress(e);
});

progress.addEventListener("pointerup",(e)=>{
  if(!dragging||e.pointerId!==scrubPointer) return;
  previewProgress(e);
  audio.currentTime=pendingTime;
  cancelScrub();
  renderProgress(audio.currentTime);
});

for(const event of ["pointercancel","lostpointercapture"]){
  progress.addEventListener(event,()=>{
    if(!dragging) return;
    cancelScrub();
    renderProgress(audio.currentTime);
  });
}

progress.addEventListener("keydown",(e)=>{
  if(dragging||!Number.isFinite(audio.duration)||audio.duration<=0) return;
  let target=audio.currentTime;
  if(e.key==="ArrowRight"||e.key==="ArrowUp") target+=5;
  else if(e.key==="ArrowLeft"||e.key==="ArrowDown") target-=5;
  else if(e.key==="Home") target=0;
  else if(e.key==="End") target=audio.duration;
  else return;
  e.preventDefault();
  audio.currentTime=clamp(target,0,audio.duration);
  renderProgress(audio.currentTime);
});


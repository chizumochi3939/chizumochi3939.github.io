let navigationFrame = 0;
const cancelNavigation = () => { cancelAnimationFrame(navigationFrame); navigationFrame = 0; };
window.scrollToSection = target => {
  cancelNavigation();
  const start = window.scrollY;
  const headerHeight = document.querySelector("body > .nav").getBoundingClientRect().height;
  const destination = () => {
    const max = Math.max(0, document.documentElement.scrollHeight - innerHeight);
    return target.id === "contact" ? max : Math.max(0, Math.min(max, target.getBoundingClientRect().top + window.scrollY - headerHeight - 20));
  };
  if (matchMedia("(prefers-reduced-motion: reduce)").matches) {
    window.scrollTo({top: destination(), behavior: "instant"});
    return;
  }
  const began = performance.now();
  const duration = Math.min(850, 420 + Math.abs(destination() - start) * .055);
  const step = now => {
    const progress = Math.min(1, (now - began) / duration);
    const eased = 1 - Math.pow(1 - progress, 3);
    window.scrollTo({top: start + (destination() - start) * eased, behavior: "instant"});
    navigationFrame = progress < 1 ? requestAnimationFrame(step) : 0;
  };
  navigationFrame = requestAnimationFrame(step);
};
for (const type of ["wheel", "touchstart", "pointerdown"]) window.addEventListener(type, cancelNavigation, {passive: true});
window.addEventListener("keydown", event => {
  if (["ArrowUp", "ArrowDown", "PageUp", "PageDown", "Home", "End", " ", "Escape"].includes(event.key)) cancelNavigation();
});
document.querySelectorAll('body > .nav a[href^="#"]').forEach(link => link.addEventListener("click", event => {
  if (event.ctrlKey || event.metaKey || event.shiftKey || event.altKey) return;
  const target = document.getElementById(link.hash.slice(1));
  if (!target) return;
  event.preventDefault();
  window.scrollToSection(target);
}));


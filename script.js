function randomTrack(){
  if(playlist.length<2) return index;
  const choice=Math.floor(Math.random()*(playlist.length-1));
  return choice>=index?choice+1:choice;
}

function randomInitialTrack(){
  if(playlist.length<2) return 0;
  try{
    const stored=sessionStorage.getItem("playerInitialTrack");
    const previous=stored===null?-1:Number(stored);
    const hasPrevious=previous>=0&&previous<playlist.length;
    const choice=Math.floor(Math.random()*(playlist.length-(hasPrevious?1:0)));
    const selected=hasPrevious&&choice>=previous?choice+1:choice;
    sessionStorage.setItem("playerInitialTrack",String(selected));
    return selected;
  }catch(_){
    return Math.floor(Math.random()*playlist.length);
  }
}

